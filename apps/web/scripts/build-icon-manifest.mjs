#!/usr/bin/env node
// Lists the artwork in public/icons for the app:
//   pnpm --filter @racktrack/web build:icons
//
// Writes src/icons/manifest.ts with each file's URL and aspect ratio (width /
// height, read from its viewBox), ready to spread into <Icon>. Run it after
// adding or replacing an SVG.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';

const publicDir = fileURLToPath(new URL('../public/', import.meta.url));
const out = fileURLToPath(new URL('../src/icons/manifest.ts', import.meta.url));

const camel = (s) => s.replace(/-([a-z])/g, (_, c) => c.toUpperCase());

const groups = [];
for (const dir of readdirSync(join(publicDir, 'icons'), { withFileTypes: true })) {
  if (!dir.isDirectory()) continue;
  const items = [];
  for (const file of readdirSync(join(publicDir, 'icons', dir.name)).filter((f) => f.endsWith('.svg')).sort()) {
    const svg = readFileSync(join(publicDir, 'icons', dir.name, file), 'utf8');
    const box = svg.match(/viewBox="([^"]+)"/)?.[1].trim().split(/\s+/).map(Number);
    if (!box || box.length !== 4) throw new Error(`icons/${dir.name}/${file}: no viewBox`);
    const aspectRatio = Math.round((box[2] / box[3]) * 1000) / 1000;
    items.push({ key: camel(file.replace(/\.svg$/, '')), src: `/icons/${dir.name}/${file}`, aspectRatio });
  }
  groups.push({ name: camel(dir.name), items });
}

const lines = [
  '// Generated by scripts/build-icon-manifest.mjs from public/icons. Do not edit by hand.',
  '// Spread an entry into the UI package\'s <Icon>: <Icon {...firearmsIcons.rifle} size="xl" />',
  '',
];
for (const g of groups) {
  lines.push(`export const ${g.name}Icons = {`);
  for (const i of g.items) {
    lines.push(`  ${i.key}: { src: '${i.src}', aspectRatio: ${i.aspectRatio} },`);
  }
  lines.push('} as const;', '');
}
writeFileSync(out, lines.join('\n'));
console.log(`Wrote ${groups.reduce((n, g) => n + g.items.length, 0)} icons to src/icons/manifest.ts`);
